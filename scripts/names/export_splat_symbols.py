"""export_splat_symbols.py [combined symbol file] [output]: the recovered names as a Splat symbol_addrs file.

Splat parses `source:` and other attributes of our provenance comments as its own, so only `type:` is kept; the
provenance stays in config/recovered/sly2_combined_symbol_addrs.txt."""
import os
import re
import sys

LAB = os.environ.get('ROGUE_BYTE_DIR') or os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
source = sys.argv[1] if len(sys.argv) > 1 else os.path.join(LAB, 'config', 'recovered', 'sly2_combined_symbol_addrs.txt')
destination = sys.argv[2] if len(sys.argv) > 2 else os.path.join(LAB, 'config', 'us', 'symbol_addrs.txt')

lines = ['// Generated by scripts/names/export_splat_symbols.py from config/recovered/sly2_combined_symbol_addrs.txt.']
for line in open(source):
    match = re.match(r'(\S+) = (0x[0-9A-Fa-f]+);(?: // (.*))?', line)
    if not match:
        continue
    name, address, comment = match.groups()
    kept = [attribute for attribute in (comment or '').split() if attribute.startswith('type:')]
    lines.append(f"{name} = {address};{' // ' + ' '.join(kept) if kept else ''}")
open(destination, 'w').write('\n'.join(lines) + '\n')
print(f'{len(lines) - 1} symbols -> {destination}')
